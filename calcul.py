def division(a, b):
    if b == 0:
        raise ValueError("Division par zéro impossible")
    

    """Calcule le quotient entre deux nombres.

    Args:
        a (int | float): Le nombre de base.
        b (int | float): Le diviseur.

    Returns:
        int | float: Le quotient entre a et b.
    """

    return a / b



    